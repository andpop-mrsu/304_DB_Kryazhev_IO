-- db_init.sql
-- Лабораторная работа 6. БД для станции технического обслуживания
-- SQLite 3

PRAGMA foreign_keys = ON;

-- ============================================================
-- DROP (в порядке, обратном зависимостям)
-- ============================================================
DROP TABLE IF EXISTS salary_payments;
DROP TABLE IF EXISTS work_log;
DROP TABLE IF EXISTS appointments;
DROP TABLE IF EXISTS master_schedule;
DROP TABLE IF EXISTS master_specializations;
DROP TABLE IF EXISTS cars;
DROP TABLE IF EXISTS clients;
DROP TABLE IF EXISTS masters;
DROP TABLE IF EXISTS services;
DROP TABLE IF EXISTS car_categories;

-- ============================================================
-- 1. Справочник категорий автомобилей
-- ============================================================
CREATE TABLE car_categories (
    id   INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT    NOT NULL UNIQUE
);

-- ============================================================
-- 2. Справочник услуг
-- ============================================================
CREATE TABLE services (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    name         TEXT    NOT NULL,
    duration_min INTEGER NOT NULL CHECK (duration_min > 0),
    price        REAL    NOT NULL CHECK (price >= 0),
    category_id  INTEGER NOT NULL,
    FOREIGN KEY (category_id) REFERENCES car_categories(id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ============================================================
-- 3. Мастера (сотрудники)
-- ============================================================
CREATE TABLE masters (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    full_name      TEXT    NOT NULL,
    phone          TEXT    UNIQUE,
    hire_date      TEXT    NOT NULL DEFAULT (date('now')),
    fire_date      TEXT,
    salary_percent REAL    NOT NULL DEFAULT 30.0
                           CHECK (salary_percent >= 0 AND salary_percent <= 100),
    is_active      INTEGER NOT NULL DEFAULT 1
                           CHECK (is_active IN (0, 1))
);

-- ============================================================
-- 4. Специализация мастеров (M:N masters ↔ services)
-- ============================================================
CREATE TABLE master_specializations (
    master_id  INTEGER NOT NULL,
    service_id INTEGER NOT NULL,
    PRIMARY KEY (master_id, service_id),
    FOREIGN KEY (master_id)  REFERENCES masters(id)  ON DELETE CASCADE,
    FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE CASCADE
);

-- ============================================================
-- 5. Индивидуальный график мастеров
-- ============================================================
CREATE TABLE master_schedule (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    master_id  INTEGER NOT NULL,
    weekday    INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6), -- 0=Пн, 6=Вс
    start_time TEXT    NOT NULL,   -- HH:MM
    end_time   TEXT    NOT NULL,   -- HH:MM
    UNIQUE (master_id, weekday),
    CHECK (end_time > start_time),
    FOREIGN KEY (master_id) REFERENCES masters(id) ON DELETE CASCADE
);

-- ============================================================
-- 6. Клиенты
-- ============================================================
CREATE TABLE clients (
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    full_name TEXT    NOT NULL,
    phone     TEXT    NOT NULL UNIQUE,
    email     TEXT    UNIQUE
);

-- ============================================================
-- 7. Автомобили клиентов
-- ============================================================
CREATE TABLE cars (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    client_id     INTEGER NOT NULL,
    category_id   INTEGER NOT NULL,
    brand         TEXT    NOT NULL,
    model         TEXT    NOT NULL,
    license_plate TEXT    NOT NULL UNIQUE,
    year          INTEGER CHECK (year BETWEEN 1900 AND 2100),
    FOREIGN KEY (client_id)   REFERENCES clients(id)        ON DELETE CASCADE,
    FOREIGN KEY (category_id) REFERENCES car_categories(id) ON DELETE RESTRICT
);

-- ============================================================
-- 8. Предварительная запись
-- ============================================================
CREATE TABLE appointments (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    client_id    INTEGER NOT NULL,
    car_id       INTEGER NOT NULL,
    master_id    INTEGER NOT NULL,
    service_id   INTEGER NOT NULL,
    scheduled_at TEXT    NOT NULL,              -- datetime
    status       TEXT    NOT NULL DEFAULT 'planned'
                         CHECK (status IN ('planned', 'done', 'cancelled')),
    created_at   TEXT    NOT NULL DEFAULT (datetime('now')),
    FOREIGN KEY (client_id)  REFERENCES clients(id)  ON DELETE CASCADE,
    FOREIGN KEY (car_id)     REFERENCES cars(id)     ON DELETE CASCADE,
    FOREIGN KEY (master_id)  REFERENCES masters(id)  ON DELETE RESTRICT,
    FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE RESTRICT
);

-- ============================================================
-- 9. Фактически выполненные работы
-- ============================================================
CREATE TABLE work_log (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    appointment_id INTEGER,
    master_id      INTEGER NOT NULL,
    service_id     INTEGER NOT NULL,
    car_id         INTEGER NOT NULL,
    completed_at   TEXT    NOT NULL DEFAULT (datetime('now')),
    price_charged  REAL    NOT NULL CHECK (price_charged >= 0),
    master_share   REAL    NOT NULL CHECK (master_share >= 0),
    FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE SET NULL,
    FOREIGN KEY (master_id)      REFERENCES masters(id)      ON DELETE RESTRICT,
    FOREIGN KEY (service_id)     REFERENCES services(id)     ON DELETE RESTRICT,
    FOREIGN KEY (car_id)         REFERENCES cars(id)         ON DELETE RESTRICT
);

-- ============================================================
-- 10. Выплаты зарплаты
-- ============================================================
CREATE TABLE salary_payments (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    master_id    INTEGER NOT NULL,
    period_start TEXT    NOT NULL,
    period_end   TEXT    NOT NULL,
    amount       REAL    NOT NULL CHECK (amount >= 0),
    paid_at      TEXT    NOT NULL DEFAULT (datetime('now')),
    CHECK (period_end >= period_start),
    FOREIGN KEY (master_id) REFERENCES masters(id) ON DELETE RESTRICT
);

-- ============================================================
-- Индексы
-- ============================================================
CREATE INDEX idx_services_category   ON services(category_id);
CREATE INDEX idx_cars_client         ON cars(client_id);
CREATE INDEX idx_appointments_master ON appointments(master_id);
CREATE INDEX idx_appointments_date   ON appointments(scheduled_at);
CREATE INDEX idx_worklog_master      ON work_log(master_id);
CREATE INDEX idx_worklog_date        ON work_log(completed_at);
CREATE INDEX idx_masters_active      ON masters(is_active);

